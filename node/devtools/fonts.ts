// Writes src/router/fonts.ts from the two font files in assets/fonts:  pnpm tsx devtools/fonts.ts
// The local console pages carry their typefaces inside the page, so the browser that opens one asks nobody for them.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const at = (p: string) => fileURLToPath(new URL(p, import.meta.url));

/** The @font-face rules for the console pages, with each font file inlined as a data: URI. */
export function fontFaces(read: (file: string) => Buffer = (f) => readFileSync(at(`../assets/fonts/${f}`))): string {
  const face = (family: string, weight: string, file: string, extra = '') =>
    `@font-face{font-family:'${family}';font-style:normal;font-weight:${weight};${extra}font-display:swap;src:url(data:font/woff2;base64,${read(file).toString('base64')}) format('woff2')}`;
  return face('Instrument Sans', '400 700', 'instrument-sans-latin.woff2', 'font-stretch:100%;') + face('Geist Mono', '100 900', 'geist-mono-latin.woff2');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(
    at('../src/router/fonts.ts'),
    [
      '// Generated by devtools/fonts.ts from assets/fonts; do not edit by hand.',
      '// The typefaces of the local console pages, carried inside the page itself: the Latin subsets of Instrument Sans and',
      '// Geist Mono (both under the SIL Open Font License 1.1; each file keeps its copyright and license in its name table).',
      `export const FONT_FACES = ${JSON.stringify(fontFaces())};`,
      '',
    ].join('\n'),
  );
  console.log('wrote src/router/fonts.ts');
}
